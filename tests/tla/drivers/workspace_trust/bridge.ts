// Connects behavior observed from the real fx binary to TLC.
//
// The observations become WorkspaceTrustObserved.tla. WorkspaceTrustTrace
// replays them through WorkspaceTrust's own actions for Design "a". ACCEPTED
// requires TLC exit 12 on the NotAllMatched sentinel, reachable only after
// every observation matched. A completed search is REJECTED; then each
// observation is replayed alone to name the first one the model cannot produce.
//
// Strict verdicts: unreadable or missing evidence is never acceptance.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TLA_ROOT, tlcToolchain } from "../lib/tlc";

export type Surface = "tui" | "headless";
export type Folder = "repo" | "worktree" | "spoof" | "home";
export type Answer = "yes" | "no" | "none";
export type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

export interface Observation {
  id: string;
  surface: Surface;
  folder: Folder;
  repoTrusted: boolean;
  answer: Answer;
  exited: boolean;
  savedAfter: boolean;
  evidence?: Record<string, unknown>;
}

export interface TraceResult {
  verdict: Verdict;
  detail: string;
  firstMismatch?: string;
  workDir?: string;
  hashes: Record<string, string>;
}

const tla = join(TLA_ROOT, "workspace_trust");

const str = (value: string) => JSON.stringify(value);
const bool = (value: boolean) => (value ? "TRUE" : "FALSE");

function observationValue(o: Observation): string {
  return `[surface |-> ${str(o.surface)}, folder |-> ${str(o.folder)}, ` +
    `repoTrusted |-> ${bool(o.repoTrusted)}, answer |-> ${str(o.answer)}, ` +
    `exited |-> ${bool(o.exited)}, savedAfter |-> ${bool(o.savedAfter)}]`;
}

export function observedModule(observations: Observation[]): string {
  return [
    "---------------------------- MODULE WorkspaceTrustObserved ----------------------------",
    "(* Generated by tests/tla/drivers/workspace_trust/bridge.ts from runtime observations. Do not edit. *)",
    `Observed == << ${observations.map(observationValue).join(",\n  ")} >>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const sha = (path: string) => createHash("sha256").update(readFileSync(path)).digest("hex");

async function runTrace(observations: Observation[], parent: string): Promise<{ verdict: Verdict; log: string; dir: string }> {
  const dir = mkdtempSync(join(parent, "trace-a-"));
  for (const file of ["WorkspaceTrust.tla", "WorkspaceTrustTrace.tla"]) {
    copyFileSync(join(tla, file), join(dir, file));
  }
  writeFileSync(join(dir, "WorkspaceTrustObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), [
    "SPECIFICATION TraceSpec",
    "CONSTANTS",
    '  Design = "a"',
    '  Mutant = "none"',
    '  Class = "ideal"',
    "INVARIANT NotAllMatched",
    "CHECK_DEADLOCK FALSE",
    "",
  ].join("\n"));
  const { java, jar } = tlcToolchain();
  mkdirSync(join(dir, ".tlc-tmp"), { recursive: true });
  const child = Bun.spawn([
    java, "-XX:+UseParallelGC", `-Djava.io.tmpdir=${join(dir, ".tlc-tmp")}`, "-cp", jar,
    "tlc2.TLC", "-workers", "1", "-metadir", join(dir, ".tlc-states"),
    "-config", "trace.cfg", "WorkspaceTrustTrace.tla",
  ], {
    cwd: dir, stdin: "ignore", stdout: "pipe", stderr: "pipe",
  });
  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  const log = `${stdout}\n${stderr}`;
  writeFileSync(join(dir, "tlc.log"), log);
  if (code === 12 && log.includes("Invariant NotAllMatched is violated")) return { verdict: "ACCEPTED", log, dir };
  if (code === 0 && log.includes("Model checking completed. No error has been found.")) return { verdict: "REJECTED", log, dir };
  return { verdict: "TOOL_ERROR", log, dir };
}

/** Replays every observation through Design "a". `parent` receives the TLC work. */
export async function checkTrace(observations: Observation[], parent: string): Promise<TraceResult> {
  const hashes = {
    "WorkspaceTrust.tla": sha(join(tla, "WorkspaceTrust.tla")),
    "WorkspaceTrustTrace.tla": sha(join(tla, "WorkspaceTrustTrace.tla")),
    observations: createHash("sha256").update(JSON.stringify(observations)).digest("hex"),
  };
  if (observations.length === 0) {
    return { verdict: "TOOL_ERROR", detail: "no observations", hashes };
  }
  const whole = await runTrace(observations, parent);
  if (whole.verdict !== "REJECTED") {
    return {
      verdict: whole.verdict,
      detail: `${observations.length} observations; TLC work ${whole.dir}`,
      workDir: whole.dir,
      hashes,
    };
  }
  for (const observation of observations) {
    const single = await runTrace([observation], parent);
    if (single.verdict === "TOOL_ERROR") {
      return {
        verdict: "TOOL_ERROR",
        workDir: single.dir,
        hashes,
        detail: `TLC error on observation ${observation.id}; TLC work ${single.dir}`,
      };
    }
    if (single.verdict !== "ACCEPTED") {
      return {
        verdict: "REJECTED",
        hashes,
        firstMismatch: observation.id,
        workDir: whole.dir,
        detail: `Design "a" cannot produce observation ${observation.id} ` +
          `(surface=${observation.surface}, folder=${observation.folder}, repoTrusted=${observation.repoTrusted}, ` +
          `answer=${observation.answer}, exited=${observation.exited}, savedAfter=${observation.savedAfter}); TLC work ${whole.dir}`,
      };
    }
  }
  return {
    verdict: "REJECTED",
    workDir: whole.dir,
    hashes,
    detail: `each observation matches alone, but not in sequence; TLC work ${whole.dir}`,
  };
}
