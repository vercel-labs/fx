// Connects runs of the real fx binary to TLC. The observations of one
// profile's run become ShellSessionObserved.tla, and
// tests/tla/session/ShellSessionTrace.tla replays them through ShellSession's
// own actions. ACCEPTED needs TLC's exit 12 on the NotAllMatched sentinel
// with every observation matched. A finished search is REJECTED; then the
// longest prefix the model can produce names the first observation it
// cannot. Strict verdicts: missing or unreadable evidence is never accepted.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { runTlc, sha256File, sha256Text, TLA_ROOT, writeJson } from "../lib/tlc";

export type Op =
  | "launch" | "launch_resume" | "launch_no_store" | "begin" | "end" | "status"
  | "new" | "clear" | "resume" | "fork" | "quit" | "crash";

/// One step of a run, with what fx showed and saved after it. Every field
/// comes from fx's own output and files; one the step does not show is
/// "none", 0 or false, as ShellSession's `Obs` leaves it.
export interface Observation {
  op: Op;
  /// The session the step opened (wiring trace) or `/status` named.
  id: string;
  /// The prompt a fork was made before, counted from 1.
  point: number;
  /// What `/status` said.
  saved: boolean;
  /// The session the exit line named.
  handoff: string;
  /// Each saved session's id and the turns its log holds.
  disk: Record<string, number>;
}

export type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

export interface TraceResult {
  verdict: Verdict;
  length: number;
  matched: number;
  detail: string;
  firstMismatch?: { step: number; observation: Observation };
  hashes: Record<string, string>;
}

const SPEC_DIR = join(TLA_ROOT, "session");
const SPECS = ["ShellSession.tla", "ShellSessionTrace.tla"];

const str = (value: string) => JSON.stringify(value);
const bool = (value: boolean) => (value ? "TRUE" : "FALSE");

function diskValue(disk: Record<string, number>): { ids: string; turns: string } {
  const ids = Object.keys(disk).sort();
  return {
    ids: `{${ids.map(str).join(", ")}}`,
    turns: ids.length === 0 ? "[i \\in {} |-> 0]" : `(${ids.map((id) => `${str(id)} :> ${disk[id]}`).join(" @@ ")})`,
  };
}

function observationValue(o: Observation): string {
  const disk = diskValue(o.disk);
  return `[op |-> ${str(o.op)}, id |-> ${str(o.id)}, point |-> ${o.point}, saved |-> ${bool(o.saved)}, ` +
    `handoff |-> ${str(o.handoff)}, disk |-> ${disk.ids}, turns |-> ${disk.turns}]`;
}

/// The ids a run named, and the most turns any log held.
function constants(observations: Observation[]): { ids: string[]; maxTurns: number } {
  const ids = new Set<string>();
  let maxTurns = 1;
  for (const o of observations) {
    for (const id of [o.id, o.handoff, ...Object.keys(o.disk)]) if (id !== "none") ids.add(id);
    for (const turns of Object.values(o.disk)) maxTurns = Math.max(maxTurns, turns);
  }
  return { ids: [...ids].sort(), maxTurns };
}

export function observedModule(observations: Observation[]): string {
  const { ids, maxTurns } = constants(observations);
  return [
    "---------------------------- MODULE ShellSessionObserved ----------------------------",
    "(* Generated by tests/tla/drivers/session/bridge.ts from one run. Do not edit. *)",
    "EXTENDS TLC",
    `TIds == {${ids.map(str).join(", ")}}`,
    `TMaxTurns == ${maxTurns}`,
    `Observed == << ${observations.map(observationValue).join(",\n  ")} >>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const TRACE_CFG = [
  "CONSTANTS",
  "  Ids <- TIds",
  "  MaxTurns <- TMaxTurns",
  '  Mutant = "none"',
  "INIT TraceInit",
  "NEXT TraceNext",
  "INVARIANT NotAllMatched",
  "CHECK_DEADLOCK FALSE",
  "",
].join("\n");

async function replay(observations: Observation[], dir: string): Promise<Verdict> {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "ShellSessionObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), TRACE_CFG);
  const run = await runTlc(dir, "ShellSessionTrace.tla", "trace.cfg", SPECS, SPEC_DIR);
  const matched = [...run.output.matchAll(/\/\\ k = (\d+)/g)].map((match) => Number(match[1])).at(-1);
  if (run.exitCode === 12 && run.violated === "NotAllMatched" && matched === observations.length) return "ACCEPTED";
  if (run.exitCode === 0 && run.output.includes("Model checking completed. No error has been found.")) return "REJECTED";
  return "TOOL_ERROR";
}

/// Replays `observations` through the model. `dir` receives every TLC run.
export async function checkTrace(observations: Observation[], dir: string): Promise<TraceResult> {
  const hashes = {
    ...Object.fromEntries(SPECS.map((name) => [name, sha256File(join(SPEC_DIR, name))])),
    observations: sha256Text(JSON.stringify(observations)),
  };
  const result = await (async (): Promise<TraceResult> => {
    const length = observations.length;
    if (length === 0) return { verdict: "TOOL_ERROR", length, matched: 0, detail: "no observations", hashes };
    const whole = await replay(observations, join(dir, "whole"));
    if (whole !== "REJECTED") {
      return { verdict: whole, length, matched: whole === "ACCEPTED" ? length : 0, detail: `TLC work in ${dir}`, hashes };
    }
    // A prefix of a behavior is a behavior, so the longest one accepted is
    // found by bisection.
    let good = 0, bad = length;
    while (bad - good > 1) {
      const mid = Math.floor((good + bad) / 2);
      const verdict = await replay(observations.slice(0, mid), join(dir, `prefix-${mid}`));
      if (verdict === "TOOL_ERROR") return { verdict, length, matched: 0, detail: `TLC failed on a prefix of ${mid}; see ${dir}`, hashes };
      if (verdict === "ACCEPTED") good = mid;
      else bad = mid;
    }
    return {
      verdict: "REJECTED", length, matched: good, hashes,
      firstMismatch: { step: good + 1, observation: observations[good]! },
      detail: `the model cannot produce step ${good + 1}: ${JSON.stringify(observations[good])}`,
    };
  })();
  writeJson(join(dir, "verdict.json"), result);
  return result;
}
