// Runs the real fx binary along tests/tla/session/AcceptedInput.tla (Design
// "a2"): launches fx in tmux with a fake gateway and the stalled HTTP MCP
// fixture across five scenarios covering Submit during a held MCP call,
// delivery at a steering boundary, retract via Up, /new, SIGKILL, -c, and
// resubmitting restored composer text as a new prompt. After each step the
// driver reads fx's session log (`input_accepted`, `input_delivered`,
// `input_withdrawn`, `item user` and `steering`) and tmux pane (`┋` rows,
// composer, scrollback notices), and TLC checks each trace against the "a2"
// spec (`AcceptedInputTrace.tla`).
//
// Planted deviations from a kept trace must be rejected, an empty trace must
// return TOOL_ERROR, and running against an fx binary built before EB-03
// (`FX_BIN=<base>`) must reject the kill scenario trace.
