interface PromptSpec {
  id: number;
  text: string;
}

function readLogSnapshot(home: string, sessionId: string) {
  const lines = logLines(home, sessionId) as any[];
  const acceptedIds = lines.filter((l) => l.kind === "input_accepted").map((l) => l.id as number);
  const deliveredIds = [...new Set(lines.filter((l) => l.kind === "input_delivered").map((l) => l.id as number))];
  const withdrawnIds = [...new Set(lines.filter((l) => l.kind === "input_withdrawn").map((l) => l.id as number))];
  const userLines = lines.filter((l) => l.kind === "item" && l.type === "user");
  const userItems = userLines.length;
  const recoveryTurns = userLines.filter((l) => JSON.stringify(l.data ?? "").includes("<session_resumed>")).length;
  const steeringItems = lines.filter((l) => l.kind === "item" && l.type === "steering").length;
  const starts = lines.filter((l) => l.kind === "turn_started").length;
  const ends = lines.filter((l) => l.kind === "turn_committed" || l.kind === "turn_interrupted").length;
  return {
    acceptedIds,
    deliveredIds,
    withdrawnIds,
    userItems,
    recoveryTurns,
    steeringItems,
    logTurnOpen: starts > ends,
  };
}

function observe(opts: {
  op: Op;
  id: number;
  home: string;
  sessionId: string;
  prompts: PromptSpec[];
  pane?: string;
  scrollback?: string;
  activeNotices?: number[];
}): Observation {
  const log = readLogSnapshot(opts.home, opts.sessionId);
  const pane = opts.pane ?? "";
  const scrollback = opts.scrollback ?? "";
  const screen = opts.pane === undefined ? [] : opts.prompts.filter((p) => hasQueuedRow(pane, p.text)).map((p) => p.id);
  const compText = opts.pane === undefined ? "" : composerText(pane);
  // Withdraw puts text back in the edit buffer locally; AcceptedInput models crash/resume composer restore.
  const composer =
    opts.pane === undefined || opts.op === "withdraw"
      ? []
      : opts.prompts.filter((p) => compText.includes(p.text)).map((p) => p.id);

  let notices: number[] = [];
  if (opts.op === "switch") {
    if (scrollback.includes(SWITCH_SINGULAR_NOTICE)) {
      notices = log.acceptedIds.filter((id) => !log.deliveredIds.includes(id) && !log.withdrawnIds.includes(id));
    }
  } else if (opts.op === "restart" || opts.op === "resume") {
    if (scrollback.includes(RESTORE_SINGULAR_NOTICE) || scrollback.includes(RESTORE_PLURAL_NOTICE)) {
      notices = [...composer];
    }
  } else if (opts.activeNotices && opts.activeNotices.length > 0) {
    notices = [...opts.activeNotices];
  }

  return {
    op: opts.op,
    id: opts.id,
    screen,
    composer,
    notices,
    acceptedIds: log.acceptedIds,
    deliveredIds: log.deliveredIds,
    withdrawnIds: log.withdrawnIds,
    userItems: log.userItems,
    steeringItems: log.steeringItems,
    recoveryTurns: log.recoveryTurns,
    turnOpen: opts.op === "crash" || opts.op === "switch" ? false : log.logTurnOpen,
  };
}

