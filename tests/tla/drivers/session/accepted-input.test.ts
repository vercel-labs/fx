const RESTORE_SINGULAR_NOTICE =
  "1 prompt you sent before fx stopped was not delivered. It is back in the composer.";
const RESTORE_PLURAL_NOTICE =
  "prompts you sent before fx stopped were not delivered. They are back in the composer.";
const SWITCH_SINGULAR_NOTICE =
  "1 queued prompt was not sent. It comes back when you reopen this session.";

type Op =
  | "turn_started"
  | "show"
  | "boundary_commit"
  | "close_turn"
  | "withdraw"
  | "switch"
  | "crash"
  | "restart"
  | "resume";

interface Observation {
  op: Op;
  id: number;
  screen: number[];
  composer: number[];
  notices: number[];
  acceptedIds: number[];
  deliveredIds: number[];
  withdrawnIds: number[];
  userItems: number;
  steeringItems: number;
  recoveryTurns: number;
  turnOpen: boolean;
}

type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

interface TraceResult {
  verdict: Verdict;
  length: number;
  matched: number;
  detail: string;
  firstMismatch?: { step: number; observation: Observation };
  hashes: Record<string, string>;
}

const SPEC_DIR = join(TLA_ROOT, "session");
const SPECS = ["AcceptedInput.tla", "AcceptedInputTrace.tla"];

const str = (value: string) => JSON.stringify(value);
const bool = (value: boolean) => (value ? "TRUE" : "FALSE");
const seq = (items: number[]) => `<<${items.join(", ")}>>`;
const set = (items: number[]) => `{${[...new Set(items)].sort((a, b) => a - b).join(", ")}}`;

function observationValue(o: Observation): string {
  return (
    `[op |-> ${str(o.op)}, id |-> ${o.id}, screen |-> ${set(o.screen)}, ` +
    `composer |-> ${seq(o.composer)}, notices |-> ${set(o.notices)}, ` +
    `acceptedIds |-> ${seq(o.acceptedIds)}, deliveredIds |-> ${set(o.deliveredIds)}, ` +
    `withdrawnIds |-> ${set(o.withdrawnIds)}, userItems |-> ${o.userItems}, ` +
    `steeringItems |-> ${o.steeringItems}, recoveryTurns |-> ${o.recoveryTurns}, ` +
    `turnOpen |-> ${bool(o.turnOpen)}]`
  );
}

function observedModule(observations: Observation[]): string {
  const maxPrompts = Math.max(
    1,
    ...observations.flatMap((o) => [o.id, ...o.acceptedIds, ...o.deliveredIds, ...o.withdrawnIds, ...o.composer, ...o.screen, ...o.notices]),
  );
  const maxCrashes = Math.max(1, observations.filter((o) => o.op === "crash").length);
  const maxSwitches = Math.max(1, observations.filter((o) => o.op === "switch").length);
  return [
    "---------------------------- MODULE AcceptedInputObserved ----------------------------",
    "(* Generated by tests/tla/drivers/session/accepted-input.test.ts from one run. Do not edit. *)",
    "EXTENDS Naturals",
    `TMaxPrompts == ${maxPrompts}`,
    `TMaxCrashes == ${maxCrashes}`,
    `TMaxSwitches == ${maxSwitches}`,
    `Observed == << ${observations.map(observationValue).join(",\n  ")} >>`,
    "======================================================================================",
    "",
  ].join("\n");
}

const TRACE_CFG = [
  "CONSTANTS",
  "  MaxPrompts <- TMaxPrompts",
  "  MaxCrashes <- TMaxCrashes",
  "  MaxSwitches <- TMaxSwitches",
  '  Design = "a2"',
  '  Mutant = "none"',
  "INIT TraceInit",
  "NEXT TraceNext",
  "INVARIANT NotAllMatched",
  "INVARIANT AcceptedSurvives",
  "CHECK_DEADLOCK FALSE",
  "",
].join("\n");

async function replay(observations: Observation[], dir: string): Promise<{ verdict: Verdict; violated: string | null }> {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "AcceptedInputObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), TRACE_CFG);
  const run = await runTlc(dir, "AcceptedInputTrace.tla", "trace.cfg", SPECS, SPEC_DIR);
  const matched = [...run.output.matchAll(/\/\\ k = (\d+)/g)].map((match) => Number(match[1])).at(-1);
  if (run.exitCode === 12 && run.violated === "NotAllMatched" && matched === observations.length) {
    return { verdict: "ACCEPTED", violated: run.violated };
  }
  if (run.exitCode === 0 && run.output.includes("Model checking completed. No error has been found.")) {
    return { verdict: "REJECTED", violated: null };
  }
  return { verdict: "TOOL_ERROR", violated: run.violated };
}

async function checkTrace(observations: Observation[], dir: string): Promise<TraceResult> {
  const hashes = {
    ...Object.fromEntries(SPECS.map((name) => [name, sha256File(join(SPEC_DIR, name))])),
    observations: sha256Text(JSON.stringify(observations)),
  };
  const length = observations.length;
  let result: TraceResult;
  if (length === 0) {
    result = { verdict: "TOOL_ERROR", length, matched: 0, detail: "no observations", hashes };
  } else {
    const whole = await replay(observations, join(dir, "whole"));
    if (whole.verdict !== "REJECTED") {
      result = {
        verdict: whole.verdict,
        length,
        matched: whole.verdict === "ACCEPTED" ? length : 0,
        detail: `TLC work in ${dir}` + (whole.violated ? ` (${whole.violated})` : ""),
        hashes,
      };
    } else {
      let good = 0;
      let bad = length;
      while (bad - good > 1) {
        const mid = Math.floor((good + bad) / 2);
        if ((await replay(observations.slice(0, mid), join(dir, `prefix-${mid}`))).verdict === "ACCEPTED") {
          good = mid;
        } else {
          bad = mid;
        }
      }
      const firstMismatch = { step: good + 1, observation: observations[good]! };
      result = {
        verdict: "REJECTED",
        length,
        matched: good,
        detail: `the model cannot produce step ${firstMismatch.step}: ${JSON.stringify(firstMismatch.observation)}`,
        firstMismatch,
        hashes,
      };
    }
  }
  writeJson(join(dir, "verdict.json"), result);
  return result;
}

