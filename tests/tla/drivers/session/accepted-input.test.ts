function createFixture(prefix: string) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), prefix)));
  const home = join(root, "home");
  const workspace = join(root, "workspace");
  mkdirSync(join(home, ".fx"), { recursive: true });
  mkdirSync(workspace);
  writeFileSync(
    join(home, ".fx", "settings.json"),
    JSON.stringify({ sandbox: "none", permission_mode: "full-access", permission: {} }),
  );
  return { root, home, workspace: realpathSync(workspace) };
}

function writeStalledMcpConfig(home: string, url: string) {
  writeFileSync(
    join(home, ".fx", "mcp.json"),
    JSON.stringify({
      mcp: {
        fixture: {
          type: "http",
          url,
          headers: { "X-Workspace": "one" },
          startup_timeout_ms: 5_000,
          operation_timeout_ms: 30_000,
        },
      },
    }),
  );
}

function gatewayEnv(home: string, gateway: ReturnType<typeof startDynamicFakeGateway>) {
  return {
    HOME: home,
    AI_GATEWAY_API_KEY: "fake-accepted-input-key",
    VERCEL_OIDC_TOKEN: undefined,
    FX_GATEWAY_BASE_URL: gateway.baseUrl,
    FX_GATEWAY_CHAT_URL: gateway.chatUrl,
    FX_MODEL: FAKE_GATEWAY_MODEL,
    FX_PERMISSION_MODE: "full-access",
    FX_DISABLE_KEYCHAIN: "1",
    FX_SOUND: "0",
    FX_AUTO_UPGRADE: "0",
    NO_COLOR: "1",
  };
}

async function launchFx(
  fixture: ReturnType<typeof createFixture>,
  gateway: ReturnType<typeof startDynamicFakeGateway>,
  args: string,
  name: string,
  extraEnv: Record<string, string | undefined> = {},
  waitEmptyComposer = true,
) {
  const stderrPath = join(fixture.root, `${name}-stderr.log`);
  writeFileSync(stderrPath, "");
  const session = await TmuxSession.create({
    cmd: `${binary} ${args}`.trim(),
    cwd: fixture.workspace,
    env: { ...gatewayEnv(fixture.home, gateway), ...extraEnv },
    stderrPath,
    width: 120,
    height: 40,
  });
  if (waitEmptyComposer) {
    await session.waitForComposer(PANE_WAIT_TIMEOUT);
  }
  return { session, stderrPath };
}

function hasQueuedRow(pane: string, marker: string): boolean {
  return pane.split("\n").some((line) => line.includes(marker) && line.trimStart().startsWith("┋"));
}

async function waitForQueuedRow(session: InstanceType<typeof TmuxSession>, marker: string): Promise<string> {
  return session.waitForPane((pane) => hasQueuedRow(pane, marker), PANE_WAIT_TIMEOUT);
}

function composerBlockLines(pane: string): string[] {
  const lines = pane.split("\n");
  const lastIndex = lines.findLastIndex((line) => isComposerLine(line));
  if (lastIndex < 0) return [];
  let startIndex = lastIndex;
  while (startIndex > 0 && isComposerLine(lines[startIndex - 1]!)) {
    startIndex -= 1;
  }
  return lines.slice(startIndex, lastIndex + 1).map((line) => {
    const trimmedStart = line.trimStart();
    if (trimmedStart.startsWith("┃ ")) return trimmedStart.slice(2).trimEnd();
    if (trimmedStart.startsWith("┃")) return trimmedStart.slice(1).trimEnd();
    if (trimmedStart.startsWith("❯ ")) return trimmedStart.slice(2).trimEnd();
    if (trimmedStart.startsWith("> ")) return trimmedStart.slice(2).trimEnd();
    return trimmedStart.slice(1).trimEnd();
  });
}

function composerText(pane: string): string {
  return composerBlockLines(pane).join("\n");
}

function processAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

async function endFx(session: InstanceType<typeof TmuxSession>, signal: "SIGKILL" | "SIGHUP") {
  const pid = session.processPid();
  process.kill(pid, signal);
  const deadline = Date.now() + 10_000;
  while (Date.now() < deadline && processAlive(pid)) await Bun.sleep(25);
  await session.kill();
}

async function waitForCondition(predicate: () => boolean, description: string, timeout = PANE_WAIT_TIMEOUT): Promise<void> {
  const deadline = Date.now() + timeout;
  while (Date.now() < deadline) {
    if (predicate()) return;
    await Bun.sleep(25);
  }
  throw new Error(`Timed out waiting for ${description}.`);
}

async function waitForResumedPaneSettled(
  session: InstanceType<typeof TmuxSession>,
  historyMarker: string,
  resumeRequested: (() => boolean) | null,
  resumedReplyMarker: string,
): Promise<{ pane: string; scrollback: string }> {
  const deadline = Date.now() + PANE_WAIT_TIMEOUT;
  while (Date.now() < deadline) {
    const pane = await session.capturePane();
    const hasComposer = pane.split("\n").some(isComposerLine);
    const hasHistory = pane.includes(historyMarker);
    const resumeDone =
      resumeRequested === null ||
      (resumeRequested() && pane.includes(resumedReplyMarker) && turnSettled(pane));
    if (hasComposer && hasHistory && resumeDone && turnSettled(pane)) {
      return {
        pane,
        scrollback: await session.captureFullScrollback(),
      };
    }
    await Bun.sleep(25);
  }
  throw new Error(`Timed out waiting for resumed session to settle.\nLast pane:\n${await session.capturePane()}`);
}

