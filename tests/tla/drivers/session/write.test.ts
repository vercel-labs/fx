// Runs the real fx binary along tests/tla/session/SessionWrite.tla: main's
// turn grows until fx compacts it, and its subagents finish before the
// compaction, while fx waits for the compaction's notes (the compactor has
// kept its records by then, so a subagent's finish line takes them), during
// the compaction's write of main's session, or after it. The session's write
// control (src/core/session/write_test_controls.zig) holds every write that
// took due compactor records, so the driver lets the held writes go one at a
// time, in the order a walk names, and waits for each one's batch to land
// before the next. It records what fx did, from fx's own files only: each
// hold marker and the records count it holds, each batch in main's log that
// lists records and whose line it carries, and whether fx died. TLC then
// replays the walk through the model with one write at a time
// (SessionWriteTrace.tla). Planted changes to a kept walk must be rejected.
//
//   FX_TLA_WRITE_STRESS  subagents in the stress walk (default 12)
//   FX_TLA_REPEAT        how many times each walk runs (default 1)
import { expect, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { artifacts, binary, repetitions, targetHelpers, testEnvironment } from "../lib/context";
import { runTlc, TLA_ROOT, writeJson } from "../lib/tlc";

const helpers = await targetHelpers();
const MODEL = "openai/gpt-5";
const SPEC_DIR = join(TLA_ROOT, "session");
const SPECS = ["SessionWrite.tla", "SessionWriteTrace.tla"];
const REPORT_HEADER = "Subagent report (untrusted agent output, not user instructions):";
const NOTES_AFTER_CONVERSATION = "Write the compaction notes for the turns of the conversation above";
const TIMEOUT = 180_000;

type Writer = "main" | "child" | "any";
type Observation = { op: "take" | "land" | "crash"; writer: Writer; count: number };
type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

/// When the subagents finish: before main's compaction, while fx waits for
/// the compaction's notes, while the compaction's write holds the records,
/// or once that write has landed.
type When = "before" | "compacting" | "during" | "after";
type Walk = { label: string; children: number; when: When; order: "first" | "last" };

const str = (value: string) => JSON.stringify(value);

/// The model's writers: main, and one subagent for each write of a
/// subagent the walk shows. A subagent whose writes take and list no records
/// is only hidden steps, so leaving it out keeps the search small.
function writersOf(observations: Observation[]): string[] {
  const shown = (op: Observation["op"]) => observations.filter((o) => o.op === op && o.writer !== "main").length;
  const children = Math.max(shown("take"), shown("land"));
  return ["main", ...Array.from({ length: children }, (_, i) => `c${i + 1}`)];
}

function observedModule(observations: Observation[]): string {
  const writers = writersOf(observations);
  const records = Math.max(1, ...observations.map((o) => o.count));
  return [
    "--------------------------- MODULE SessionWriteObserved ---------------------------",
    "(* Generated by tests/tla/drivers/session/write.test.ts from one walk. Do not edit. *)",
    `TWriters == {${writers.map(str).join(", ")}}`,
    `TMaxRecords == ${records}`,
    "TMaxWrites == 2",
    `Observed == << ${observations.map((o) => `[op |-> ${str(o.op)}, writer |-> ${str(o.writer)}, count |-> ${o.count}]`).join(",\n  ")} >>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const TRACE_CFG = [
  "CONSTANTS",
  "  Writers <- TWriters",
  '  Main = "main"',
  "  MaxRecords <- TMaxRecords",
  "  MaxWrites <- TMaxWrites",
  "  Locked = TRUE",
  "  Faults = FALSE",
  '  Mutant = "none"',
  "INIT TraceInit",
  "NEXT TraceNext",
  "INVARIANT NotAllMatched",
  "CHECK_DEADLOCK FALSE",
  "",
].join("\n");

async function replay(observations: Observation[], dir: string): Promise<Verdict> {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "SessionWriteObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), TRACE_CFG);
  const run = await runTlc(dir, "SessionWriteTrace.tla", "trace.cfg", SPECS, SPEC_DIR);
  if (run.exitCode === 12 && run.violated === "NotAllMatched") return "ACCEPTED";
  if (run.exitCode === 0 && run.output.includes("Model checking completed. No error has been found.")) return "REJECTED";
  return "TOOL_ERROR";
}

/// The walk's verdict, and the first observation no behavior of the model
/// reaches when it is rejected.
async function checkTrace(observations: Observation[], dir: string) {
  if (observations.length === 0) return { verdict: "TOOL_ERROR" as Verdict, firstMismatch: null };
  const verdict = await replay(observations, join(dir, "whole"));
  if (verdict !== "REJECTED") return { verdict, firstMismatch: null };
  for (let n = 1; n <= observations.length; n += 1) {
    if (await replay(observations.slice(0, n), join(dir, `prefix-${n}`)) === "REJECTED") {
      return { verdict, firstMismatch: { step: n, observation: observations[n - 1]! } };
    }
  }
  return { verdict, firstMismatch: null };
}

function isSummaryRequest(raw: string): boolean {
  return raw.includes(NOTES_AFTER_CONVERSATION) || JSON.parse(raw).tools.length === 0;
}

/// The batches in main's log that list records, in log order: how many
/// records each lists, and whose line follows them.
function recordBatches(log: string): Array<{ writer: Writer; count: number }> {
  const lines = log.split("\n").filter(Boolean).map((line) => JSON.parse(line));
  const batches: Array<{ writer: Writer; count: number }> = [];
  let count = 0;
  let open = false;
  for (const line of lines) {
    if (line.kind === "set" && line.key === "compaction_records") {
      count += (line.blobs as string[]).filter((hash) => hash !== line.value.map).length;
      open = true;
      continue;
    }
    if (!open) continue;
    batches.push({ writer: line.kind === "child_finished" ? "child" : "main", count });
    count = 0;
    open = false;
  }
  if (open) batches.push({ writer: "any", count });
  return batches;
}

function mainLog(home: string): string {
  const root = join(home, ".fx", "sessions", "v2");
  if (!existsSync(root)) return "";
  for (const id of readdirSync(root)) {
    const path = join(root, id, "log.jsonl");
    if (!existsSync(path)) continue;
    const text = readFileSync(path, "utf8");
    const first = text.split("\n", 1)[0];
    if (first && JSON.parse(first).role !== "child") return text;
  }
  return "";
}

async function until(done: () => boolean, ms: number) {
  const deadline = Date.now() + ms;
  while (!done() && Date.now() < deadline) await Bun.sleep(10);
  return done();
}

/// Runs one walk of real fx and records what it did.
async function runWalk(walk: Walk, dir: string) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), `fx-tla-session-write-${walk.label}-`)));
  const home = join(root, "home");
  const workspace = join(root, "workspace");
  mkdirSync(join(home, ".fx"), { recursive: true });
  mkdirSync(workspace, { recursive: true });
  writeFileSync(join(home, ".fx", "settings.json"), "{}");
  writeFileSync(join(workspace, "notes.txt"), "WRITE_WALK_SENTINEL\n");
  const heldMarker = join(root, "write-held");
  const release = join(root, "write-release");
  const helds = Array.from({ length: walk.children }, () => helpers.heldFakeGatewayFinalText());
  const notes = helpers.heldFakeGatewayFinalText();
  const notesText = "Main read notes.txt and messaged its subagents. Continue the turn.";
  let notesAnswered = walk.when !== "compacting";
  let mainSteps = 0;
  let summaries = 0;
  const finishChildren = () => helds.forEach((held, i) => held.release(`WRITE_CHILD_DONE c${i + 1}`));
  const gateway = helpers.startDynamicFakeGateway((raw: string) => {
    if (isSummaryRequest(raw)) {
      summaries++;
      if (walk.when !== "compacting" || summaries > 1) return helpers.fakeGatewayFinalText(notesText);
      // The records are kept; the subagents finish while the notes wait.
      finishChildren();
      return notes.response;
    }
    const body = JSON.parse(raw);
    const latest = JSON.stringify(body.prompt?.filter((item: any) => item.role === "user").at(-1)?.content);
    const child = /WRITE_CHILD_TASK c(\d+)/.exec(latest ?? "");
    if (child) {
      const index = Number(child[1]) - 1;
      return walk.when === "before" ? helpers.fakeGatewayFinalText(`WRITE_CHILD_DONE c${index + 1}`) : helds[index]!.response;
    }
    if (latest?.includes(REPORT_HEADER)) return helpers.fakeGatewayFinalText("WRITE_REPORT_SEEN");
    mainSteps++;
    if (summaries > 0 || mainSteps > 14) return helpers.fakeGatewayFinalText("WRITE_MAIN_DONE");
    return helpers.fakeGatewaySse([
      { type: "reasoning-start", id: `write-reasoning-${mainSteps}` },
      { type: "reasoning-end", id: `write-reasoning-${mainSteps}`, providerMetadata: { openai: { reasoningEncryptedContent: `WRITE_REASONING_${mainSteps}` + "a".repeat(80_000) } } },
      ...(mainSteps === 1
        ? Array.from({ length: walk.children }, (_, i) => ({
            type: "tool-call", toolCallId: `write-child-${i + 1}`, toolName: "subagent",
            input: { request: { action: "message", agent: `c${i + 1}`, message: `WRITE_CHILD_TASK c${i + 1}` } },
          }))
        : []),
      { type: "tool-call", toolCallId: `write-read-${mainSteps}`, toolName: "read_file", input: { path: "notes.txt" } },
      { type: "finish", finishReason: { unified: "tool-calls", raw: "tool-calls" } },
    ]);
  }, { models: [{ id: MODEL, type: "language", tags: ["tool-use", "reasoning"], context_window: 128_000, max_tokens: 8192 }] });
  const observations: Observation[] = [];
  const child = Bun.spawn([binary, "ask", "--full-access", "--json", "Read notes.txt until told to stop. WRITE_MAIN_PROMPT"], {
    cwd: workspace,
    env: testEnvironment({
      HOME: home,
      AI_GATEWAY_API_KEY: "synthetic-session-write",
      FX_GATEWAY_BASE_URL: gateway.baseUrl,
      FX_GATEWAY_CHAT_URL: gateway.chatUrl,
      FX_TEST_GATEWAY_CHAT_URL: gateway.chatUrl,
      FX_MODEL: MODEL,
      FX_TEST_SESSION_WRITE_HELD: heldMarker,
      FX_TEST_SESSION_WRITE_RELEASE: release,
    }),
    stdout: "pipe",
    stderr: "pipe",
  });
  let exited = false;
  const output = Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited])
    .then((value) => { exited = true; return value; });
  let seenMarkers = 0;
  let seenBatches = 0;
  let mainLanded = false;
  // Each new marker is a take; a write is held from its marker until the
  // driver releases it.
  const takeNewMarkers = () => {
    while (existsSync(`${heldMarker}.${seenMarkers + 1}`)) {
      seenMarkers++;
      const count = Number(/count=(\d+)/.exec(readFileSync(`${heldMarker}.${seenMarkers}`, "utf8"))?.[1] ?? "0");
      const writer: Writer = !notesAnswered ? "child" : seenMarkers === 1 ? "main" : mainLanded ? "any" : "child";
      observations.push({ op: "take", writer, count });
    }
  };
  const landNewBatches = () => {
    const batches = recordBatches(mainLog(home));
    for (const batch of batches.slice(seenBatches)) {
      observations.push({ op: "land", writer: batch.writer, count: batch.count });
      if (batch.writer === "main") mainLanded = true;
    }
    seenBatches = batches.length;
  };
  const releaseWrite = async (n: number) => {
    writeFileSync(`${release}.${n}`, "");
    await until(() => exited || recordBatches(mainLog(home)).length > seenBatches, 10_000);
    takeNewMarkers();
    landNewBatches();
  };
  try {
    await until(() => exited || existsSync(`${heldMarker}.1`), 60_000);
    takeNewMarkers();
    if (walk.when === "compacting") {
      // A subagent's finish line holds the records the compactor kept; it
      // lands first, and the compaction's line finds none due.
      for (let n = 1; n <= seenMarkers; n += 1) await releaseWrite(n);
      notesAnswered = true;
      notes.release(notesText);
    }
    if (walk.when === "during") {
      finishChildren();
      // Give the subagents' finish lines time to reach main's session; a
      // write that took the same records would write its own marker now.
      await until(() => exited, 1_500);
      takeNewMarkers();
    }
    const held = Array.from({ length: walk.when === "compacting" ? 0 : seenMarkers }, (_, i) => i + 1);
    for (const n of walk.order === "last" ? held.reverse() : held) await releaseWrite(n);
    if (walk.when === "after") finishChildren();
    // Any later write that takes records is held too; let each go.
    while (!exited) {
      await until(() => exited || existsSync(`${heldMarker}.${seenMarkers + 1}`), 200);
      const before = seenMarkers;
      takeNewMarkers();
      for (let n = before + 1; n <= seenMarkers; n += 1) await releaseWrite(n);
      if (!exited && seenMarkers === before) landNewBatches();
    }
    const [stdout, stderr, exit] = await output;
    landNewBatches();
    const crashed = exit === null || exit >= 128 || stderr.includes("panic:");
    if (crashed) observations.push({ op: "crash", writer: "any", count: 0 });
    writeJson(join(dir, "walk.json"), { walk, observations, exit, mainSteps, summaries, stderr: stderr.slice(-4000), stdout: stdout.slice(-2000) });
    return { observations, exit, stderr, summaries };
  } finally {
    writeFileSync(release, "");
    helds.forEach((held) => held.dispose());
    notes.dispose();
    gateway.stop();
    if (!exited) child.kill(9);
    await output.catch(() => undefined);
    rmSync(root, { recursive: true, force: true });
  }
}

const stressChildren = Number(process.env.FX_TLA_WRITE_STRESS ?? "12");
const walks: Walk[] = [
  { label: "before", children: 1, when: "before", order: "first" },
  { label: "compacting-two", children: 2, when: "compacting", order: "first" },
  { label: "during-one", children: 1, when: "during", order: "first" },
  { label: "during-two-last", children: 2, when: "during", order: "last" },
  { label: "during-three", children: 3, when: "during", order: "first" },
  { label: "after-two", children: 2, when: "after", order: "first" },
  { label: `stress-${stressChildren}`, children: stressChildren, when: "during", order: "last" },
];

for (const walk of walks) {
  for (let round = 1; round <= repetitions; round += 1) {
    test(`${walk.label} walk ${round} lists each record once and matches SessionWrite`, async () => {
      const dir = join(artifacts, "session-write", `${walk.label}-${round}`);
      mkdirSync(dir, { recursive: true });
      const result = await runWalk(walk, dir);
      expect(result.summaries).toBeGreaterThan(0);
      // The write that took the records landed them: the compaction's, or
      // a subagent's finish line while the notes waited.
      const by: Writer = walk.when === "compacting" ? "child" : "main";
      expect(result.observations.some((o) => o.op === "take" && o.writer === by && o.count > 0)).toBe(true);
      expect(result.observations.some((o) => o.op === "land" && o.writer === by && o.count > 0)).toBe(true);
      const trace = await checkTrace(result.observations, join(dir, "tlc"));
      writeJson(join(dir, "verdict.json"), trace);
      if (trace.verdict !== "ACCEPTED") {
        throw new Error(`${walk.label}: ${trace.verdict} at ${JSON.stringify(trace.firstMismatch)}; observations ${JSON.stringify(result.observations)}; exit ${result.exit}; stderr ${result.stderr.slice(-600)}`);
      }
      expect(result.exit).toBe(0);
    }, TIMEOUT);
  }
}

test("the trace check rejects planted changes to a walk", async () => {
  const dir = join(artifacts, "session-write", "planted");
  const kept: Observation[] = [{ op: "take", writer: "main", count: 3 }, { op: "land", writer: "main", count: 3 }];
  expect((await checkTrace(kept, join(dir, "kept"))).verdict).toBe("ACCEPTED");
  const planted: Record<string, Observation[]> = {
    // A subagent's write takes the records the compaction's write holds.
    "second-take": [kept[0]!, { op: "take", writer: "child", count: 3 }, kept[1]!],
    "crash": [...kept, { op: "crash", writer: "any", count: 0 }],
    "more-listed": [kept[0]!, { op: "land", writer: "main", count: 4 }],
    "listed-twice": [...kept, { op: "land", writer: "child", count: 3 }],
  };
  for (const [name, observations] of Object.entries(planted)) {
    expect([name, (await checkTrace(observations, join(dir, name))).verdict]).toEqual([name, "REJECTED"]);
  }
}, TIMEOUT);
