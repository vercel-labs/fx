/// The newest user text of a Gateway request, which says whose turn it is.
function latestUser(body: string): string {
  const prompt: any[] = JSON.parse(body).prompt ?? [];
  const user = prompt.filter((message) => message.role === "user").at(-1);
  if (!user) return "";
  if (typeof user.content === "string") return user.content;
  return (user.content ?? []).map((part: any) => (typeof part?.text === "string" ? part.text : "")).join("");
}

const isChild = (body: string) => !body.includes('"name":"subagent"');
const isReport = (body: string) => latestUser(body).includes("Subagent report (untrusted agent output, not user instructions):");

class Profile {
  readonly root = mkdtempSync(join(tmpdir(), "fx-tla-live-"));
  readonly home = realpathSync((mkdirSync(join(this.root, "home")), join(this.root, "home")));
  readonly workspace = realpathSync((mkdirSync(join(this.root, "workspace")), join(this.root, "workspace")));
  /// Requests the gateway holds, by the tag in their prompt, until released.
  private readonly held = new Map<string, (response: Response) => void>();
  readonly gateway = startDynamicFakeGateway(async (body: string) => {
    if (isReport(body)) return fakeGatewayFinalText("LIVE_DRIVER_REPORT_READ");
    const text = latestUser(body);
    const tag = /LIVEDRV (\w+) (\w+)/.exec(text);
    if (!tag) return fakeGatewayFinalText("LIVE_DRIVER_PLAIN");
    const [, name, role] = tag;
    if (role === "delegate" && !isChild(body)) {
      if (body.includes(`drv-${name}`)) return fakeGatewayFinalText(`LIVE_DRIVER_SENT_${name}`);
      return fakeGatewayToolCall(`drv-${name}`, "subagent", { request: { action: "message", agent: AGENT, message: `LIVEDRV ${name} child` } });
    }
    return new Promise<Response>((resolve) => this.held.set(`${name}:${role}`, resolve));
  }, { classifierDecision: "clear" });

  env(): Record<string, string> {
    return testEnvironment({
      HOME: this.home,
      AI_GATEWAY_API_KEY: "live-driver-key",
      FX_GATEWAY_BASE_URL: this.gateway.baseUrl,
      FX_GATEWAY_CHAT_URL: this.gateway.chatUrl,
      FX_TEST_GATEWAY_CHAT_URL: this.gateway.chatUrl,
      FX_MODEL: FAKE_GATEWAY_MODEL,
    });
  }

  store(): string {
    return join(this.home, ".fx", "sessions", "v2");
  }

  roots(): string[] {
    if (!existsSync(this.store())) return [];
    return readdirSync(this.store()).filter((id) => {
      const log = join(this.store(), id, "log.jsonl");
      return existsSync(log) && JSON.parse(readFileSync(log, "utf8").split("\n", 1)[0]!).role === "root";
    });
  }

  log(id: string): any[] {
    return readFileSync(join(this.store(), id, "log.jsonl"), "utf8").split("\n").filter(Boolean).map((line) => JSON.parse(line));
  }

  isHeld(key: string): boolean {
    return this.held.has(key);
  }

  release(key: string, text: string) {
    const resolve = this.held.get(key);
    if (!resolve) throw new Error(`nothing held as ${key}`);
    this.held.delete(key);
    resolve(fakeGatewayFinalText(text));
  }

  ask(args: string[]): { child: ChildProcess; exited: Promise<number | null> } {
    const child = spawn(binary, ["ask", "--json", "--auto", ...args], { cwd: this.workspace, env: this.env(), stdio: "ignore" });
    const exited = new Promise<number | null>((resolve) => child.on("exit", (code) => resolve(code)));
    return { child, exited };
  }

  async command(args: string[]): Promise<{ code: number; stdout: string; stderr: string }> {
    const proc = Bun.spawn([binary, ...args], { cwd: this.workspace, env: this.env(), stdout: "pipe", stderr: "pipe" });
    const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited]);
    return { code, stdout, stderr };
  }

  async live(): Promise<any> {
    const result = await this.command(["sessions", "--live", "--all", "--json"]);
    if (result.code !== 0 || result.stderr !== "") throw new Error(`fx sessions --live failed: ${result.code} ${result.stderr}`);
    return JSON.parse(result.stdout);
  }

  close() {
    this.gateway.stop();
    rmSync(this.root, { recursive: true, force: true });
  }
}

async function until(check: () => boolean, what: string, ms = 30_000) {
  const deadline = Date.now() + ms;
  while (!check()) {
    if (Date.now() > deadline) throw new Error(`timed out waiting for ${what}`);
    await Bun.sleep(20);
  }
}

