// Runs the real fx binary along tests/tla/session/LiveSessions.tla. `fx ask`
// processes open saved sessions, hold a turn, start a named subagent, finish,
// and are killed, while `fx sessions --live --all --json` scans between their
// steps. The driver records each step it took and each scan's output, and
// TLC replays the whole run through the model (LiveSessionsTrace.tla): every
// listing must be the one the model's state gives at that point. A planted
// change to a kept run must be rejected, and an empty run is no evidence.
//
// Two checks need no model. Scans in a tight loop while other fx processes
// resume the same sessions never make one of those opens fail, and a scan
// killed partway leaves no lock held: the next scan lists nothing and every
// session opens again.
//
//   FX_TLA_WALKS        random walks (default 2) of FX_TLA_STEPS steps
//                       (default 14), from FX_TLA_SEED (default 1)
//   FX_TLA_RACE_ROUNDS  resumes raced against scans (default 12)
//   FX_TLA_KILLS        scans killed partway (default 12)
import { expect, test } from "bun:test";
import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { artifacts, binary, targetModule, testEnvironment } from "../lib/context";
import { runTlc, sha256File, sha256Text, TLA_ROOT, writeJson } from "../lib/tlc";

const { startDynamicFakeGateway, fakeGatewayFinalText, fakeGatewayToolCall, FAKE_GATEWAY_MODEL } = await targetModule("tmux-helpers.ts");

const TIMEOUT = 600_000;
const PROCS = ["p1", "p2"] as const;
const SLOTS = ["s1", "s2"] as const;
const AGENT = "alpha";

type Proc = (typeof PROCS)[number];
type Slot = (typeof SLOTS)[number];
type Op = "open" | "acquire" | "begin" | "end" | "spawn" | "finish" | "exit" | "crash" | "scan_start" | "scan_end";
type Listed = { id: Slot; working: boolean; agents: { name: string; st: string }[] };
type Observation = { op: Op; p: string; s: string; n: string; listed: Listed[] };

