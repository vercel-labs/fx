// The walk

type Holder = { slot: Slot; tag: string; delegating: boolean; process: ReturnType<Profile["ask"]> };

/// What the driver did, and nothing it expects fx to show: which process
/// holds which session, and the real id behind each of the model's sessions.
class Walk {
  readonly observations: Observation[] = [];
  readonly holders = new Map<Proc, Holder>();
  readonly ids = new Map<Slot, string>();
  private tags = 0;

  constructor(readonly profile: Profile) {}

  private note(op: Op, p = "none", s = "none", n = "none", listed: Listed[] = []) {
    this.observations.push({ op, p, s, n, listed });
  }

  slotOf(id: string): Slot {
    for (const [slot, known] of this.ids) if (known === id) return slot;
    throw new Error(`fx listed ${id}, a session the driver never opened`);
  }

  freeSlots(): Slot[] {
    const held = new Set([...this.holders.values()].map((holder) => holder.slot));
    return SLOTS.filter((slot) => !held.has(slot));
  }

  /// Process `p` opens `slot`, new or saved, and holds a turn; with
  /// `delegate` that turn starts the subagent, ends, and leaves it working.
  async hold(p: Proc, slot: Slot, delegate: boolean) {
    const tag = `t${++this.tags}`;
    const role = delegate ? "delegate" : "main";
    const known = this.ids.get(slot);
    const before = this.profile.roots();
    const committed = known ? this.profile.log(known).filter((line) => line.kind === "turn_committed").length : 0;
    const process = this.profile.ask([...(known ? ["--resume", known] : []), `LIVEDRV ${tag} ${role}`]);
    this.holders.set(p, { slot, tag, delegating: delegate, process });
    this.note("open", p, slot);
    this.note("acquire", p);
    this.note("begin", p);
    await until(() => this.profile.isHeld(`${tag}:${delegate ? "child" : "main"}`), `${tag} to be held`);
    if (!known) {
      const fresh = this.profile.roots().filter((id) => !before.includes(id));
      if (fresh.length !== 1) throw new Error(`expected one new session, found ${fresh.join(",")}`);
      this.ids.set(slot, fresh[0]!);
    }
    if (delegate) {
      const id = this.ids.get(slot)!;
      await until(() => this.profile.log(id).filter((line) => line.kind === "turn_committed").length > committed, `${tag}'s turn to end`);
      this.note("spawn", p, "none", AGENT);
      this.note("end", p);
    }
  }

  async crash(p: Proc) {
    const holder = this.holders.get(p)!;
    holder.process.child.kill("SIGKILL");
    await holder.process.exited;
    this.holders.delete(p);
    this.note("crash", p);
  }

  /// The held turn, or the held subagent and the report turn it starts,
  /// finishes, and the process exits.
  async release(p: Proc) {
    const holder = this.holders.get(p)!;
    if (holder.delegating) {
      this.profile.release(`${holder.tag}:child`, `LIVE_DRIVER_CHILD_${holder.tag}`);
      this.note("finish", p, "none", AGENT);
      this.note("begin", p);
    } else {
      this.profile.release(`${holder.tag}:main`, `LIVE_DRIVER_DONE_${holder.tag}`);
    }
    const code = await holder.process.exited;
    if (code !== 0) throw new Error(`${holder.tag} exited ${code}`);
    this.holders.delete(p);
    this.note("end", p);
    this.note("exit", p);
  }

  async scan() {
    const listed = (await this.profile.live()).sessions.map((entry: any): Listed => {
      if (entry.state !== "working" && entry.state !== "idle") throw new Error(`state ${entry.state} for ${entry.id}`);
      return {
        id: this.slotOf(entry.id),
        working: entry.state === "working",
        agents: entry.agents.map((agent: any) => ({ name: agent.name, st: agent.state })),
      };
    });
    this.note("scan_start");
    this.note("scan_end", "none", "none", "none", listed);
  }

  /// Every step the walk could take next.
  choices(): Array<() => Promise<void>> {
    const out: Array<() => Promise<void>> = [() => this.scan()];
    for (const p of PROCS) {
      const holder = this.holders.get(p);
      if (holder) {
        out.push(() => this.crash(p), () => this.release(p));
      } else {
        for (const slot of this.freeSlots()) out.push(() => this.hold(p, slot, false), () => this.hold(p, slot, true));
      }
    }
    return out;
  }

  async stop() {
    for (const holder of this.holders.values()) holder.process.child.kill("SIGKILL");
    await Promise.all([...this.holders.values()].map((holder) => holder.process.exited));
  }
}

function rng(seed: number) {
  let state = seed >>> 0 || 1;
  return () => {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    return (state >>> 0) / 0x100000000;
  };
}

/// The scripted walk: each action of the model, a crash that leaves a turn
/// and a subagent's work open, a resume that repairs them, and scans between.
async function scripted(walk: Walk) {
  await walk.scan();
  await walk.hold("p1", "s1", false);
  await walk.scan();
  await walk.hold("p2", "s2", true);
  await walk.scan();
  await walk.crash("p2");
  await walk.scan();
  await walk.hold("p2", "s2", false);
  await walk.scan();
  await walk.release("p1");
  await walk.scan();
  await walk.release("p2");
  await walk.scan();
  await walk.hold("p1", "s1", true);
  await walk.scan();
  await walk.release("p1");
  await walk.scan();
}

test("the scripted walk is a behavior of LiveSessions, and a changed run is not", async () => {
  const profile = new Profile();
  const walk = new Walk(profile);
  try {
    await scripted(walk);
  } finally {
    await walk.stop();
    profile.close();
  }
  writeJson(join(artifacts, "scripted.json"), walk.observations);
  const ops = new Set(walk.observations.map((o) => o.op));
  for (const op of ["open", "acquire", "begin", "end", "spawn", "finish", "exit", "crash", "scan_start", "scan_end"]) expect(ops.has(op as Op)).toBe(true);
  // The walk saw a working subagent of an idle session, and that subagent idle after a resume.
  expect(walk.observations.some((o) => o.listed.some((e) => !e.working && e.agents.some((a) => a.st === "working")))).toBe(true);
  expect(walk.observations.some((o) => o.listed.some((e) => e.agents.some((a) => a.st === "idle")))).toBe(true);

  const kept = await checkTrace(walk.observations, join(artifacts, "scripted"));
  expect(kept.detail).toBeDefined();
  expect(kept.verdict).toBe("ACCEPTED");

  // A listing that shows the subagent of a crashed and resumed session still
  // working, as if crash repair had not run, is not a behavior.
  const planted = structuredClone(walk.observations);
  const target = planted.find((o) => o.listed.some((e) => e.agents.some((a) => a.st === "idle")))!;
  for (const entry of target.listed) for (const agent of entry.agents) agent.st = "working";
  expect((await checkTrace(planted, join(artifacts, "planted-child"))).verdict).toBe("REJECTED");
  // Nor is a listing that misses a held session.
  const missing = structuredClone(walk.observations);
  missing.find((o) => o.listed.length > 0)!.listed.pop();
  expect((await checkTrace(missing, join(artifacts, "planted-missing"))).verdict).toBe("REJECTED");
  // Nor is a crashed session that is still listed.
  const stale = structuredClone(walk.observations);
  const crashAt = stale.findIndex((o) => o.op === "crash");
  const before = stale.slice(0, crashAt).filter((o) => o.op === "scan_end").at(-1)!;
  stale.find((o, index) => index > crashAt && o.op === "scan_end")!.listed = structuredClone(before.listed);
  expect((await checkTrace(stale, join(artifacts, "planted-stale"))).verdict).toBe("REJECTED");
  expect((await checkTrace([], join(artifacts, "empty"))).verdict).toBe("TOOL_ERROR");
}, TIMEOUT);

test("random walks are behaviors of LiveSessions", async () => {
  const walks = Number(process.env.FX_TLA_WALKS ?? "2");
  const steps = Number(process.env.FX_TLA_STEPS ?? "14");
  const seed = Number(process.env.FX_TLA_SEED ?? "1");
  for (let index = 0; index < walks; index += 1) {
    const random = rng(seed + index);
    const profile = new Profile();
    const walk = new Walk(profile);
    try {
      for (let step = 0; step < steps; step += 1) {
        const choices = walk.choices();
        await choices[Math.floor(random() * choices.length)]!();
      }
      await walk.scan();
    } finally {
      await walk.stop();
      profile.close();
    }
    writeJson(join(artifacts, `walk-${seed + index}.json`), walk.observations);
    const result = await checkTrace(walk.observations, join(artifacts, `walk-${seed + index}`));
    expect(result.detail).toBeDefined();
    expect(result.verdict).toBe("ACCEPTED");
  }
}, TIMEOUT);

test("scans in a tight loop never make an open of the same sessions fail", async () => {
  const rounds = Number(process.env.FX_TLA_RACE_ROUNDS ?? "12");
  const profile = new Profile();
  try {
    const ids: string[] = [];
    for (const name of ["race-a", "race-b", "race-c"]) {
      const first = profile.ask([`A ${name} question.`]);
      expect(await first.exited).toBe(0);
    }
    ids.push(...profile.roots());
    expect(ids).toHaveLength(3);
    let scanning = true;
    let scans = 0;
    const failures: string[] = [];
    const loop = (async () => {
      while (scanning) {
        const result = await profile.command(["sessions", "--live", "--all", "--json"]);
        if (result.code !== 0 || result.stderr !== "") failures.push(`scan: ${result.code} ${result.stderr}`);
        scans += 1;
      }
    })();
    const loops = [loop, (async () => {
      while (scanning) {
        const result = await profile.command(["sessions", "--live", "--all"]);
        if (result.code !== 0) failures.push(`text scan: ${result.code} ${result.stderr}`);
        scans += 1;
      }
    })()];
    for (let round = 0; round < rounds; round += 1) {
      const resumes = ids.map((id) => profile.ask(["--resume", id, `A race round ${round}.`]));
      const codes = await Promise.all(resumes.map((resume) => resume.exited));
      codes.forEach((code, index) => {
        if (code !== 0) failures.push(`resume of ${ids[index]} in round ${round} exited ${code}`);
      });
    }
    scanning = false;
    await Promise.all(loops);
    writeJson(join(artifacts, "race.json"), { rounds, scans, failures });
    expect(failures).toEqual([]);
    expect(scans).toBeGreaterThan(rounds);
    for (const id of ids) expect(profile.log(id).filter((line) => line.kind === "turn_committed")).toHaveLength(rounds + 1);
  } finally {
    profile.close();
  }
}, TIMEOUT);

test("a scan killed partway leaves no lock held", async () => {
  const kills = Number(process.env.FX_TLA_KILLS ?? "12");
  const profile = new Profile();
  try {
    // Enough saved sessions that a scan takes a while to probe them all.
    for (let batch = 0; batch < 15; batch += 1) {
      const asks = Array.from({ length: 8 }, (_, index) => profile.ask([`A kill question ${batch}-${index}.`]));
      expect(await Promise.all(asks.map((one) => one.exited))).toEqual(Array(8).fill(0));
    }
    const random = rng(Number(process.env.FX_TLA_SEED ?? "1"));
    let killed = 0;
    for (let round = 0; round < kills; round += 1) {
      const scan = Bun.spawn([binary, "sessions", "--live", "--all", "--json"], { cwd: profile.workspace, env: profile.env(), stdout: "ignore", stderr: "ignore" });
      await Bun.sleep(Math.floor(random() * 20));
      scan.kill("SIGKILL");
      if ((await scan.exited) !== 0) killed += 1;
      // Nothing is held: no session reads as live, and each opens at once.
      expect((await profile.live()).sessions).toEqual([]);
    }
    const ids = profile.roots();
    const started = Date.now();
    const opens = ids.slice(0, 5).map((id) => profile.ask(["--resume", id, "After the killed scans."]));
    expect(await Promise.all(opens.map((open) => open.exited))).toEqual([0, 0, 0, 0, 0]);
    writeJson(join(artifacts, "kills.json"), { kills, killed, openMs: Date.now() - started });
    expect(killed).toBeGreaterThan(0);
  } finally {
    profile.close();
  }
}, TIMEOUT);
