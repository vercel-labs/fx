// TLC

const SPEC_DIR = join(TLA_ROOT, "session");
const SPECS = ["LiveSessions.tla", "LiveSessionsTrace.tla"];
const str = (value: string) => JSON.stringify(value);

function listedValue(listed: Listed[]): string {
  const entries = listed.map((entry) => {
    const agents = entry.agents.map((agent) => `[name |-> ${str(agent.name)}, st |-> ${str(agent.st)}]`);
    return `[id |-> ${str(entry.id)}, working |-> ${entry.working ? "TRUE" : "FALSE"}, agents |-> {${agents.join(", ")}}]`;
  });
  return `{${entries.join(", ")}}`;
}

function observedModule(observations: Observation[]): string {
  const value = (o: Observation) =>
    `[op |-> ${str(o.op)}, p |-> ${str(o.p)}, s |-> ${str(o.s)}, n |-> ${str(o.n)}, listed |-> ${listedValue(o.listed)}]`;
  return [
    "---------------------------- MODULE LiveSessionsObserved ----------------------------",
    "(* Generated by tests/tla/drivers/session/live.test.ts from one run. Do not edit. *)",
    `TSessions == {${SLOTS.map(str).join(", ")}}`,
    `TProcs == {${PROCS.map(str).join(", ")}}`,
    `TNames == {${str(AGENT)}}`,
    `Observed == << ${observations.map(value).join(",\n  ")} >>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const TRACE_CFG = [
  "CONSTANTS",
  "  Sessions <- TSessions",
  "  Procs <- TProcs",
  "  Names <- TNames",
  "  Wait = 1",
  "  InvertedProbe = FALSE",
  "  ProbeKeepsLock = FALSE",
  "  ListClosed = FALSE",
  "  ChildTakesParent = FALSE",
  "  RecentIsLive = FALSE",
  "INIT TraceInit",
  "NEXT TraceNext",
  "INVARIANT NotAllMatched",
  "CHECK_DEADLOCK FALSE",
  "",
].join("\n");

type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

async function replay(observations: Observation[], dir: string): Promise<Verdict> {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "LiveSessionsObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), TRACE_CFG);
  const run = await runTlc(dir, "LiveSessionsTrace.tla", "trace.cfg", SPECS, SPEC_DIR);
  const matched = [...run.output.matchAll(/\/\\ k = (\d+)/g)].map((match) => Number(match[1])).at(-1);
  if (run.exitCode === 12 && run.violated === "NotAllMatched" && matched === observations.length) return "ACCEPTED";
  if (run.exitCode === 0 && run.output.includes("Model checking completed. No error has been found.")) return "REJECTED";
  return "TOOL_ERROR";
}

/// Replays `observations` through the model; on a rejection, finds the first
/// step the model cannot take by bisection, since a prefix of a behavior is a
/// behavior.
async function checkTrace(observations: Observation[], dir: string) {
  const hashes = {
    ...Object.fromEntries(SPECS.map((name) => [name, sha256File(join(SPEC_DIR, name))])),
    observations: sha256Text(JSON.stringify(observations)),
  };
  let result: { verdict: Verdict; matched: number; detail: string };
  if (observations.length === 0) {
    result = { verdict: "TOOL_ERROR", matched: 0, detail: "no observations" };
  } else {
    const whole = await replay(observations, join(dir, "whole"));
    if (whole !== "REJECTED") {
      result = { verdict: whole, matched: whole === "ACCEPTED" ? observations.length : 0, detail: `TLC work in ${dir}` };
    } else {
      let good = 0, bad = observations.length;
      while (bad - good > 1) {
        const mid = Math.floor((good + bad) / 2);
        if ((await replay(observations.slice(0, mid), join(dir, `prefix-${mid}`))) === "ACCEPTED") good = mid;
        else bad = mid;
      }
      result = { verdict: "REJECTED", matched: good, detail: `the model cannot produce step ${good + 1}: ${JSON.stringify(observations[good])}` };
    }
  }
  writeJson(join(dir, "verdict.json"), { ...result, length: observations.length, hashes });
  return result;
}

