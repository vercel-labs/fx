// Connects behavior observed from the real fx binary to TLC.
//
// The observations become LaunchObserved.tla. LaunchTrace replays them through
// LaunchSelection's own actions for one design. ACCEPTED requires TLC exit 12
// on the NotAllMatched sentinel, reachable only after every observation
// matched. A completed search is REJECTED; then each observation is replayed
// alone to name the first one the design cannot produce.
//
// Strict verdicts: unreadable or missing evidence is never acceptance.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { TLA_ROOT, tlcToolchain } from "../lib/tlc";
import type { Notice, Outcome, Scenario } from "./scenarios";

export type Design = "current" | "proposed";
export type Verdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

export interface ObservedRequest {
  present: boolean;
  model: string;
  indicator: "on" | "off" | "unobserved";
  wireFast: boolean;
  wireUltra: boolean;
  wireEffort: "supported" | "none" | "other";
}

export interface Observation {
  id: string;
  scenario: Scenario;
  /** The early-submit race: either interleaving may explain the result. */
  orderFree: boolean;
  outcome: Outcome;
  notices: Notice[];
  req: ObservedRequest;
  evidence: Record<string, unknown>;
}

export interface TraceResult {
  design: Design;
  verdict: Verdict;
  detail: string;
  firstMismatch?: string;
  hashes: Record<string, string>;
}

const tla = join(TLA_ROOT, "cli");

const str = (value: string) => JSON.stringify(value);
const bool = (value: boolean) => (value ? "TRUE" : "FALSE");

function scenarioValue(s: Scenario): string {
  return `[path |-> ${str(s.path)}, model |-> ${str(s.model)}, speed |-> ${str(s.speed)}, ` +
    `effort |-> ${str(s.effort)}, catalog |-> ${str(s.catalog)}, fastCap |-> ${bool(s.fastCap)}, ` +
    `ultraCap |-> ${bool(s.ultraCap)}, early |-> ${bool(s.early)}]`;
}

function observationValue(o: Observation): string {
  const r = o.req;
  return `[sc |-> ${scenarioValue(o.scenario)}, orderFree |-> ${bool(o.orderFree)}, ` +
    `outcome |-> ${str(o.outcome)}, notices |-> {${o.notices.map(str).join(", ")}}, ` +
    `req |-> [present |-> ${bool(r.present)}, model |-> ${str(r.model)}, indicator |-> ${str(r.indicator)}, ` +
    `wireFast |-> ${bool(r.wireFast)}, wireUltra |-> ${bool(r.wireUltra)}, wireEffort |-> ${str(r.wireEffort)}]]`;
}

export function observedModule(observations: Observation[]): string {
  return [
    "---------------------------- MODULE LaunchObserved ----------------------------",
    "(* Generated by bun/bridge.ts from runtime observations. Do not edit. *)",
    `Observed == << ${observations.map(observationValue).join(",\n  ")} >>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const sha = (path: string) => createHash("sha256").update(readFileSync(path)).digest("hex");

async function runTrace(observations: Observation[], design: Design, parent: string): Promise<{ verdict: Verdict; log: string; dir: string }> {
  const dir = mkdtempSync(join(parent, `trace-${design}-`));
  for (const file of ["LaunchSelection.tla", "LaunchTrace.tla"]) copyFileSync(join(tla, file), join(dir, file));
  writeFileSync(join(dir, "LaunchObserved.tla"), observedModule(observations));
  writeFileSync(join(dir, "trace.cfg"), [
    "SPECIFICATION TraceSpec",
    "CONSTANTS",
    `  Design = ${str(design)}`,
    '  Mutant = "none"',
    '  Class = "all"',
    "INVARIANT NotAllMatched",
    "CHECK_DEADLOCK FALSE",
    "",
  ].join("\n"));
  const { java, jar } = tlcToolchain();
  mkdirSync(join(dir, ".tlc-tmp"), { recursive: true });
  const child = Bun.spawn([java, "-XX:+UseParallelGC", `-Djava.io.tmpdir=${join(dir, ".tlc-tmp")}`, "-cp", jar, "tlc2.TLC", "-workers", "1",
    "-metadir", join(dir, ".tlc-states"), "-config", "trace.cfg", "LaunchTrace.tla"], {
    cwd: dir, stdin: "ignore", stdout: "pipe", stderr: "pipe",
  });
  const [stdout, stderr, code] = await Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited]);
  const log = `${stdout}\n${stderr}`;
  writeFileSync(join(dir, "tlc.log"), log);
  if (code === 12 && log.includes("Invariant NotAllMatched is violated")) return { verdict: "ACCEPTED", log, dir };
  if (code === 0 && log.includes("Model checking completed. No error has been found.")) return { verdict: "REJECTED", log, dir };
  return { verdict: "TOOL_ERROR", log, dir };
}

/** Replays every observation through one design. `parent` receives the TLC work. */
export async function checkTrace(observations: Observation[], design: Design, parent: string): Promise<TraceResult> {
  const hashes = {
    "LaunchSelection.tla": sha(join(tla, "LaunchSelection.tla")),
    "LaunchTrace.tla": sha(join(tla, "LaunchTrace.tla")),
    observations: createHash("sha256").update(JSON.stringify(observations)).digest("hex"),
  };
  if (observations.length === 0) return { design, verdict: "TOOL_ERROR", detail: "no observations", hashes };
  const whole = await runTrace(observations, design, parent);
  if (whole.verdict !== "REJECTED") {
    return { design, verdict: whole.verdict, detail: `${observations.length} observations; TLC work ${whole.dir}`, hashes };
  }
  for (const observation of observations) {
    const single = await runTrace([observation], design, parent);
    if (single.verdict !== "ACCEPTED") {
      return {
        design, verdict: "REJECTED", hashes, firstMismatch: observation.id,
        detail: `${design} design cannot produce observation ${observation.id} ` +
          `(outcome=${observation.outcome}, notices=[${observation.notices}], req=${JSON.stringify(observation.req)})`,
      };
    }
  }
  return { design, verdict: "REJECTED", hashes, detail: "each observation matches alone, but not in sequence" };
}
