// Scripted trace validation for the flight recorder (`src/core/flight_recorder/`):
// drives `flight-recorder-lab script` through scripted actions and real SIGKILLs
// (reserve-heavy burst, concurrent segment switch, fail_prealloc drops, and
// size-cap eviction), reopens with `flight-recorder-lab read`, and has TLC check
// every run against `FlightRecorder.tla` via `FlightRecorderTrace.tla`.
// Pattern follows `tests/tla/drivers/session/write.test.ts` (`SessionWriteTrace.tla`).
import { expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { artifacts, testEnvironment, worktree } from "../lib/context";
import { runTlc, TLA_ROOT } from "../lib/tlc";

type SegObservation = {
  name: string;
  instance: number;
  index: number;
  sealed: boolean;
  is_current: boolean;
  is_next: boolean;
  frames: number;
  torn: number;
  holes: number;
  missing: number;
  overflowed: number;
  dropped: number;
};

type GapObservation = {
  name: string;
  instance: number;
  index: number;
  events: number;
  frames: number;
  bytes: number;
};

type ScriptObservation = {
  op: string;
  ok: boolean;
  running: boolean;
  instance: number;
  next_ready: boolean;
  fail_prealloc: boolean;
  segments: SegObservation[];
  gaps: GapObservation[];
  total_frames: number;
  total_torn: number;
  total_holes: number;
  total_missing: number;
  total_overflowed: number;
  total_dropped: number;
  total_gap_events: number;
  emitted_count: number;
  error?: string;
};

type ThreadSummary = {
  thread: number;
  count: number;
  highest: number | null;
  ranges: Array<[number, number]>;
};

type ReadSummary = {
  threads: ThreadSummary[];
  frames: number;
  torn: number;
  holes: number;
  missing: number;
  overflowed: number;
  dropped: number;
  gap_events: number;
  newer: number;
};

type TraceEntry = {
  op: "start" | "emit" | "fill_segment" | "tick" | "fail_prealloc_on" | "stop" | "crash" | "reopen";
  thread: "ui" | "worker";
  failPrealloc: boolean;
  nextReady: boolean;
  segFrames: number[];
  dropped: number;
  gapEvents: number;
  emittedTotal: number;
  isBurst: boolean;
  emittedMin: number;
  emittedMax: number;
  maxUi: number;
  maxWorker: number;
  frames: number;
  torn: number;
  holes: number;
  missing: number;
};

type TlcVerdict = "ACCEPTED" | "REJECTED" | "TOOL_ERROR";

const SPEC_DIR = join(TLA_ROOT, "flight_recorder");
const SPECS = ["FlightRecorder.tla", "FlightRecorderTrace.tla"];
const SEGMENT_BYTES = 4096;
const PAYLOAD_BYTES = 1300; // frameBytes(1300) = 1360; 2 frames fit in 4096 - 64 = 4032 (SegCap = 2)
const SEG_CAP = 2;
const MAX_U64 = 0xffff_ffff_ffff_ffffn;

const labBinary =
  process.env.FX_FLIGHT_RECORDER_LAB ?? join(worktree, "zig-out", "bin", "flight-recorder-lab");

function ensureLabBinary() {
  if (!existsSync(labBinary)) {
    throw new Error(`missing ${labBinary}; run: zig build flight-recorder-lab`);
  }
}

function str(value: string): string {
  return JSON.stringify(value);
}

function tlaBool(value: boolean): string {
  return value ? "TRUE" : "FALSE";
}

function tlaSeq(nums: number[]): string {
  return `<<${nums.join(", ")}>>`;
}

function formatEntry(e: TraceEntry): string {
  return [
    `[op |-> ${str(e.op)}`,
    `thread |-> ${str(e.thread)}`,
    `failPrealloc |-> ${tlaBool(e.failPrealloc)}`,
    `nextReady |-> ${tlaBool(e.nextReady)}`,
    `segFrames |-> ${tlaSeq(e.segFrames)}`,
    `dropped |-> ${e.dropped}`,
    `gapEvents |-> ${e.gapEvents}`,
    `emittedTotal |-> ${e.emittedTotal}`,
    `isBurst |-> ${tlaBool(e.isBurst)}`,
    `emittedMin |-> ${e.emittedMin}`,
    `emittedMax |-> ${e.emittedMax}`,
    `maxUi |-> ${e.maxUi}`,
    `maxWorker |-> ${e.maxWorker}`,
    `frames |-> ${e.frames}`,
    `torn |-> ${e.torn}`,
    `holes |-> ${e.holes}`,
    `missing |-> ${e.missing}]`,
  ].join(", ");
}

function observedModule(entries: TraceEntry[], maxEvents: number, maxSegs: number): string {
  return [
    "--------------------------- MODULE FlightRecorderObserved ---------------------------",
    "(* Generated by tests/tla/drivers/flight_recorder/trace.test.ts. Do not edit. *)",
    `TMaxEvents == ${Math.max(1, maxEvents)}`,
    `TSegCap == ${SEG_CAP}`,
    `TMaxSegs == ${maxSegs}`,
    "TMaxInstances == 2",
    `Observed == <<\n  ${entries.map(formatEntry).join(",\n  ")}\n>>`,
    "=============================================================================",
    "",
  ].join("\n");
}

const TRACE_CFG = [
  "CONSTANTS",
  '  Design = "mmap"',
  '  Mutant = "none"',
  "  AllowFaults = TRUE",
  "  AllowReset = FALSE",
  "  MaxEvents <- TMaxEvents",
  "  SegCap <- TSegCap",
  "  MaxSegs <- TMaxSegs",
  "  RingCap = 2",
  "  MaxInstances <- TMaxInstances",
  "  MaxConv = 1",
  "INIT TraceInit",
  "NEXT TraceNext",
  "INVARIANT NotAllMatched",
  "CHECK_DEADLOCK FALSE",
  "",
].join("\n");

async function replayWithTlc(
  entries: TraceEntry[],
  maxEvents: number,
  maxSegs: number,
  dir: string,
): Promise<{ verdict: TlcVerdict; output: string }> {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "FlightRecorderObserved.tla"), observedModule(entries, maxEvents, maxSegs));
  writeFileSync(join(dir, "trace.cfg"), TRACE_CFG);
  const run = await runTlc(dir, "FlightRecorderTrace.tla", "trace.cfg", SPECS, SPEC_DIR);
  if (run.exitCode === 12 && run.violated === "NotAllMatched") {
    return { verdict: "ACCEPTED", output: run.output };
  }
  if (run.exitCode === 0 && run.output.includes("Model checking completed. No error has been found.")) {
    return { verdict: "REJECTED", output: run.output };
  }
  return { verdict: "TOOL_ERROR", output: run.output };
}

const READY_LINE = '{"ready":true}';

class LabScriptClient {
  private proc: ReturnType<typeof Bun.spawn>;
  private lines: string[] = [];
  private waiters: Array<(line: string) => void> = [];
  private buffered = "";

  constructor(segDir: string) {
    this.proc = Bun.spawn([labBinary, "script", segDir], {
      env: testEnvironment({}),
      stdin: "pipe",
      stdout: "pipe",
      stderr: "pipe",
    });
    const reader = (this.proc.stdout as ReadableStream<Uint8Array>).getReader();
    const decoder = new TextDecoder();
    (async () => {
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        this.buffered += decoder.decode(value, { stream: true });
        let newline = this.buffered.indexOf("\n");
        while (newline >= 0) {
          const line = this.buffered.slice(0, newline);
          this.buffered = this.buffered.slice(newline + 1);
          const waiter = this.waiters.shift();
          if (waiter) waiter(line);
          else this.lines.push(line);
          newline = this.buffered.indexOf("\n");
        }
      }
    })();
  }

  private nextLine(): Promise<string> {
    const existing = this.lines.shift();
    if (existing !== undefined) return Promise.resolve(existing);
    return new Promise((resolve, reject) => {
      // R2.3: a deadline, so a lab that stops answering fails the test instead of hanging it.
      const timer = setTimeout(() => reject(new Error("lab script timed out waiting for stdout")), 15_000);
      this.waiters.push((line) => {
        clearTimeout(timer);
        resolve(line);
      });
    });
  }

  sendRaw(action: Record<string, unknown>) {
    const stdin = this.proc.stdin as import("bun").FileSink;
    stdin.write(`${JSON.stringify(action)}\n`);
    stdin.flush();
  }

  async waitForReady(): Promise<void> {
    const line = await this.nextLine();
    if (line !== READY_LINE) throw new Error(`lab script sent "${line}" instead of ready`);
  }

  async waitForStarted(count: number): Promise<void> {
    const expected = JSON.stringify({ started: count });
    const line = await this.nextLine();
    if (line !== expected) throw new Error(`lab script sent "${line}" instead of ${expected}`);
  }

  async send(action: Record<string, unknown>): Promise<ScriptObservation> {
    this.sendRaw(action);
    const raw = await this.nextLine();
    const obs = JSON.parse(raw) as ScriptObservation;
    if (!obs.ok) {
      throw new Error(`lab script op=${obs.op} failed: ${obs.error ?? "unknown error"}`);
    }
    return obs;
  }

  async sigkill(): Promise<void> {
    if (this.proc.exitCode === null) {
      try {
        process.kill(this.proc.pid, "SIGKILL");
      } catch {
        // Exited concurrently.
      }
    }
    await this.proc.exited;
  }

  async close(): Promise<void> {
    if (this.proc.exitCode === null) {
      (this.proc.stdin as import("bun").FileSink).end();
      await this.proc.exited;
    }
  }
}

function readBurstProgress(path: string, threadCount: number): Array<{ started: number; completed: number }> {
  const bytes = readFileSync(path);
  expect(bytes.byteLength).toBe(threadCount * 2 * 8);
  const out: Array<{ started: number; completed: number }> = [];
  for (let t = 0; t < threadCount; t += 1) {
    const rawStarted = bytes.readBigUInt64LE(t * 2 * 8);
    const rawCompleted = bytes.readBigUInt64LE((t * 2 + 1) * 8);
    out.push({
      started: rawStarted === MAX_U64 ? 0 : Number(rawStarted) + 1,
      completed: rawCompleted === MAX_U64 ? 0 : Number(rawCompleted) + 1,
    });
  }
  return out;
}

function runLabRead(segDir: string): ReadSummary {
  const proc = Bun.spawnSync([labBinary, "read", segDir], {
    env: testEnvironment({}),
    stdout: "pipe",
    stderr: "pipe",
  });
  if (proc.exitCode !== 0) {
    throw new Error(`lab read failed: ${proc.stderr.toString()}`);
  }
  return JSON.parse(proc.stdout.toString().trim()) as ReadSummary;
}

function toLiveEntry(
  op: TraceEntry["op"],
  obs: ScriptObservation,
  thread: "ui" | "worker" = "ui",
): TraceEntry {
  const activeSegs = obs.segments.filter((s) => !s.is_next);
  return {
    op,
    thread,
    failPrealloc: obs.fail_prealloc,
    nextReady: obs.next_ready,
    segFrames: activeSegs.map((s) => s.frames),
    dropped: obs.total_dropped,
    gapEvents: obs.total_gap_events,
    emittedTotal: obs.emitted_count,
    isBurst: false,
    emittedMin: 0,
    emittedMax: 0,
    maxUi: 0,
    maxWorker: 0,
    frames: 0,
    torn: 0,
    holes: 0,
    missing: 0,
  };
}

function toCrashEntry(
  emittedMin: number,
  emittedMax: number,
  isBurst: boolean,
  maxUi = 0,
  maxWorker = 0,
): TraceEntry {
  return {
    op: "crash",
    thread: "ui",
    failPrealloc: false,
    nextReady: false,
    segFrames: [],
    dropped: 0,
    gapEvents: 0,
    emittedTotal: 0,
    isBurst,
    emittedMin,
    emittedMax,
    maxUi,
    maxWorker,
    frames: 0,
    torn: 0,
    holes: 0,
    missing: 0,
  };
}

function toReopenEntry(summary: ReadSummary): TraceEntry {
  return {
    op: "reopen",
    thread: "ui",
    failPrealloc: false,
    nextReady: false,
    segFrames: [],
    dropped: summary.dropped,
    gapEvents: summary.gap_events,
    emittedTotal: 0,
    isBurst: false,
    emittedMin: 0,
    emittedMax: 0,
    maxUi: 0,
    maxWorker: 0,
    frames: summary.frames,
    torn: summary.torn,
    holes: summary.holes,
    missing: summary.missing,
  };
}

function assertReadOrder(summary: ReadSummary) {
  expect(summary.newer).toBe(0);
  for (const t of summary.threads) {
    if (t.count === 0) continue;
    expect(t.highest).not.toBeNull();
    let totalInRanges = 0;
    for (const [start, end] of t.ranges) {
      expect(start).toBeLessThanOrEqual(end);
      totalInRanges += end - start + 1;
    }
    expect(totalInRanges).toBe(t.count);
  }
}

test("trace 1: clean emit, segment switch, tick seal, and stop conform to FlightRecorder.tla", async () => {
  ensureLabBinary();
  const root = join(artifacts, `trace-clean-${Date.now()}-${process.pid}`);
  const segDir = join(root, "segs");
  const tlcDir = join(root, "tlc");
  mkdirSync(segDir, { recursive: true, mode: 0o700 });

  const client = new LabScriptClient(segDir);
  try {
    const entries: TraceEntry[] = [];
    const s1 = await client.send({
      op: "start",
      segment_bytes: SEGMENT_BYTES,
      payload_bytes: PAYLOAD_BYTES,
      sync_ms: 60_000,
      instance: 1,
    });
    expect(s1.next_ready).toBe(true);
    entries.push(toLiveEntry("start", s1));

    const s2 = await client.send({ op: "emit", thread: "ui" });
    entries.push(toLiveEntry("emit", s2, "ui"));

    const s3 = await client.send({ op: "emit", thread: "worker" });
    entries.push(toLiveEntry("emit", s3, "worker"));

    const s4 = await client.send({ op: "fill_segment", thread: "ui" });
    entries.push(toLiveEntry("fill_segment", s4, "ui"));
    expect(s4.segments.filter((s) => !s.is_next).length).toBe(2);

    const s5 = await client.send({ op: "tick" });
    entries.push(toLiveEntry("tick", s5));
    expect(s5.segments[0]!.sealed).toBe(true);
    expect(s5.next_ready).toBe(true);

    const s6 = await client.send({ op: "stop" });
    entries.push(toLiveEntry("stop", s6));
    await client.close();

    const summary = runLabRead(segDir);
    assertReadOrder(summary);
    expect(summary.frames).toBe(3);
    expect(summary.dropped).toBe(0);
    expect(summary.torn).toBe(0);
    expect(summary.missing).toBe(0);
    entries.push(toReopenEntry(summary));

    const res = await replayWithTlc(entries, 4, 10, tlcDir);
    if (res.verdict !== "ACCEPTED") throw new Error(`TLC rejected trace 1:\n${res.output}`);
  } finally {
    await client.close();
    rmSync(root, { recursive: true, force: true });
  }
}, 60_000);

