test("trace 5: SIGKILL after size-cap eviction conforms to FlightRecorder.tla", async () => {
  ensureLabBinary();
  const root = join(artifacts, `trace-evict-${Date.now()}-${process.pid}`);
  const segDir = join(root, "segs");
  const tlcDir = join(root, "tlc");
  mkdirSync(segDir, { recursive: true, mode: 0o700 });

  const client = new LabScriptClient(segDir);
  try {
    const entries: TraceEntry[] = [];
    // 13000 bytes allows 2 active 4096-byte segments + 1 preallocated next (12288 bytes),
    // and triggers eviction on the 3rd active segment + next (16384 > 13000), matching MaxSegs = 2.
    const s1 = await client.send({
      op: "start",
      segment_bytes: SEGMENT_BYTES,
      max_session_bytes: 13_000,
      payload_bytes: PAYLOAD_BYTES,
      sync_ms: 60_000,
      instance: 5,
    });
    entries.push(toLiveEntry("start", s1));

    const s2 = await client.send({ op: "fill_segment", thread: "ui" });
    entries.push(toLiveEntry("fill_segment", s2, "ui"));

    const s3 = await client.send({ op: "tick" });
    entries.push(toLiveEntry("tick", s3));

    const s4 = await client.send({ op: "fill_segment", thread: "worker" });
    entries.push(toLiveEntry("fill_segment", s4, "worker"));

    const s5 = await client.send({ op: "tick" });
    entries.push(toLiveEntry("tick", s5));
    expect(s5.gaps.length).toBeGreaterThanOrEqual(1);
    expect(s5.total_gap_events).toBeGreaterThan(0);

    await client.sigkill();
    entries.push(toCrashEntry(s5.emitted_count, s5.emitted_count, false));

    const summary = runLabRead(segDir);
    assertReadOrder(summary);
    expect(summary.gap_events).toBe(s5.total_gap_events);
    entries.push(toReopenEntry(summary));

    const res = await replayWithTlc(entries, 5, 2, tlcDir);
    if (res.verdict !== "ACCEPTED") throw new Error(`TLC rejected trace 5:\n${res.output}`);
  } finally {
    await client.sigkill();
    rmSync(root, { recursive: true, force: true });
  }
}, 60_000);

