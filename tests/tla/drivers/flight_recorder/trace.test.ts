test("trace 3: SIGKILL mid-switch during concurrent burst conforms to FlightRecorder.tla", async () => {
  ensureLabBinary();
  const root = join(artifacts, `trace-switch-kill-${Date.now()}-${process.pid}`);
  const segDir = join(root, "segs");
  const progressPath = join(root, "burst-progress.bin");
  const tlcDir = join(root, "tlc");
  mkdirSync(segDir, { recursive: true, mode: 0o700 });

  const client = new LabScriptClient(segDir);
  try {
    const entries: TraceEntry[] = [];
    const s1 = await client.send({
      op: "start",
      segment_bytes: SEGMENT_BYTES,
      payload_bytes: PAYLOAD_BYTES,
      sync_ms: 60_000,
      instance: 3,
    });
    entries.push(toLiveEntry("start", s1));

    client.sendRaw({
      op: "burst",
      threads: 2,
      events_per_thread: 6,
      delay_us: 2000,
      progress_path: progressPath,
      signal_after_started: 3,
    });

    await client.waitForReady();
    await client.waitForStarted(3);

    await client.sigkill();
    const progress = readBurstProgress(progressPath, 2);

    const emittedMin = progress[0]!.completed + progress[1]!.completed;
    const emittedMax = progress[0]!.started + progress[1]!.started;
    expect(emittedMax).toBeGreaterThanOrEqual(3);

    entries.push(
      toCrashEntry(emittedMin, emittedMax, true, progress[0]!.started, progress[1]!.started),
    );

    const summary = runLabRead(segDir);
    assertReadOrder(summary);
    expect(summary.torn + summary.missing).toBeLessThanOrEqual(2);
    entries.push(toReopenEntry(summary));

    const maxPerThread = Math.max(progress[0]!.started, progress[1]!.started, 1);
    const res = await replayWithTlc(entries, maxPerThread, 10, tlcDir);
    if (res.verdict !== "ACCEPTED") throw new Error(`TLC rejected trace 3:\n${res.output}`);
  } finally {
    await client.sigkill();
    rmSync(root, { recursive: true, force: true });
  }
}, 60_000);

