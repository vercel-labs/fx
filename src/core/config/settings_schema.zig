//! `fx config schema`: a JSON Schema for the profile `settings.json` or a
//! project `.fx.json`, built from the settings list so editors can complete
//! and check those files. fx.sh serves a copy at each file's `$id`.

const std = @import("std");
const settings_keys = @import("settings_keys.zig");

pub const File = enum {
    /// The profile `settings.json`.
    profile,
    /// A project `.fx.json`.
    project,

    /// Where fx.sh serves this schema, for a file's `$schema`.
    pub fn url(self: File) []const u8 {
        return switch (self) {
            .profile => "https://fx.sh/schemas/settings.json",
            .project => "https://fx.sh/schemas/fx.json",
        };
    }
};

/// Where in a file a key may appear.
const Place = enum { profile, workspace, project };

/// Writes the schema for `file` as indented JSON with a trailing newline.
pub fn write(writer: *std.Io.Writer, file: File) !void {
    var jw: std.json.Stringify = .{ .writer = writer, .options = .{ .whitespace = .indent_2 } };
    try jw.beginObject();
    try field(&jw, "$schema", "https://json-schema.org/draft/2020-12/schema");
    try field(&jw, "$id", file.url());
    switch (file) {
        .profile => {
            try field(&jw, "title", "fx settings");
            try field(&jw, "description", "The fx profile settings file, ~/.fx/settings.json. Generated by fx config schema.");
        },
        .project => {
            try field(&jw, "title", "fx project settings");
            try field(&jw, "description", "A project's .fx.json, which holds the defaults that are safe to commit. Generated by fx config schema --project.");
        },
    }
    try writeObjectBody(&jw, if (file == .profile) .profile else .project);
    if (file == .profile) {
        try jw.objectField("$defs");
        try jw.beginObject();
        try jw.objectField("workspace");
        try jw.beginObject();
        try field(&jw, "description", "Settings for one workspace. fx reads the workspace's directories and project MCP approvals here, and any other preference it holds.");
        try writeObjectBody(&jw, .workspace);
        try jw.endObject();
        try jw.endObject();
    }
    try jw.endObject();
    try writer.writeByte('\n');
}

fn includes(place: Place, key: settings_keys.Key) bool {
    return switch (place) {
        .profile => !key.workspace_only,
        .workspace => !key.top_level_only,
        .project => key.where == .project_safe or key.where == .editor,
    };
}

/// `type`, `properties` for every key that may appear in `place`, and no
/// other keys: the same ones `fx doctor` reports as unknown.
fn writeObjectBody(jw: *std.json.Stringify, place: Place) !void {
    try field(jw, "type", "object");
    try jw.objectField("properties");
    try jw.beginObject();
    for (settings_keys.keys) |key| {
        if (!includes(place, key)) continue;
        try jw.objectField(key.name);
        try writeKey(jw, key);
    }
    try jw.endObject();
    try jw.objectField("additionalProperties");
    try jw.write(false);
}

fn writeKey(jw: *std.json.Stringify, key: settings_keys.Key) !void {
    try jw.beginObject();
    try field(jw, "description", key.description);
    if (key.deprecated()) {
        try jw.objectField("deprecated");
        try jw.write(true);
    }
    switch (key.kind) {
        .any => {},
        .boolean => try field(jw, "type", "boolean"),
        .integer => {
            try field(jw, "type", "integer");
            if (key.minimum) |minimum| {
                try jw.objectField("minimum");
                try jw.write(minimum);
            }
            if (key.maximum) |maximum| {
                try jw.objectField("maximum");
                try jw.write(maximum);
            }
        },
        .string => {
            try field(jw, "type", "string");
            if (key.values.len > 0) {
                try jw.objectField("enum");
                try jw.write(key.values);
            }
        },
        .string_or_null => {
            try jw.objectField("type");
            try jw.write(&[_][]const u8{ "string", "null" });
        },
        .strings => {
            try field(jw, "type", "array");
            try jw.objectField("items");
            try jw.beginObject();
            try field(jw, "type", "string");
            try jw.endObject();
            if (key.max_items) |max_items| {
                try jw.objectField("maxItems");
                try jw.write(max_items);
            }
        },
        .string_map => {
            try field(jw, "type", "object");
            try jw.objectField("additionalProperties");
            try jw.beginObject();
            try field(jw, "type", "string");
            try jw.endObject();
        },
        .switches => {
            try field(jw, "type", "object");
            try jw.objectField("properties");
            try jw.beginObject();
            for (key.children, key.child_descriptions) |child, description| {
                try jw.objectField(child);
                try jw.beginObject();
                try field(jw, "description", description);
                try field(jw, "type", "boolean");
                try jw.endObject();
            }
            try jw.endObject();
            try jw.objectField("additionalProperties");
            try jw.write(false);
        },
        .object => try field(jw, "type", "object"),
        .workspaces => {
            try field(jw, "type", "object");
            try jw.objectField("additionalProperties");
            try jw.beginObject();
            try field(jw, "$ref", "#/$defs/workspace");
            try jw.endObject();
        },
        // No value is valid: fx refuses a file that sets the key.
        .refused => {
            try jw.objectField("not");
            try jw.beginObject();
            try jw.endObject();
        },
    }
    try jw.endObject();
}

fn field(jw: *std.json.Stringify, name: []const u8, value: []const u8) !void {
    try jw.objectField(name);
    try jw.write(value);
}

fn parseSchema(alloc: std.mem.Allocator, file: File) !std.json.Parsed(std.json.Value) {
    var out: std.Io.Writer.Allocating = .init(alloc);
    defer out.deinit();
    try write(&out.writer, file);
    try std.testing.expect(std.mem.endsWith(u8, out.written(), "}\n"));
    return std.json.parseFromSlice(std.json.Value, alloc, out.written(), .{});
}

test "the settings.json schema lists every key fx reads there and nothing else" {
    const parsed = try parseSchema(std.testing.allocator, .profile);
    defer parsed.deinit();
    const root = parsed.value.object;
    try std.testing.expectEqualStrings(File.profile.url(), root.get("$id").?.string);
    try std.testing.expect(!root.get("additionalProperties").?.bool);
    const properties = root.get("properties").?.object;
    const workspace = root.get("$defs").?.object.get("workspace").?.object;
    const workspace_properties = workspace.get("properties").?.object;
    try std.testing.expect(!workspace.get("additionalProperties").?.bool);
    for (settings_keys.keys) |key| {
        try std.testing.expectEqual(!key.workspace_only, properties.contains(key.name));
        try std.testing.expectEqual(!key.top_level_only, workspace_properties.contains(key.name));
    }

    try std.testing.expectEqualStrings("#/$defs/workspace", properties.get("workspaces").?.object.get("additionalProperties").?.object.get("$ref").?.string);
    const mode = properties.get("permission_mode").?.object;
    try std.testing.expectEqual(@as(usize, 4), mode.get("enum").?.array.items.len);
    const percent = properties.get("auto_compact_percent").?.object;
    try std.testing.expectEqual(@as(i64, 80), percent.get("maximum").?.integer);
    const status_line = properties.get("status_line").?.object;
    try std.testing.expectEqualStrings("boolean", status_line.get("properties").?.object.get("context").?.object.get("type").?.string);
    try std.testing.expect(!status_line.contains("deprecated"));
    try std.testing.expect(properties.get("statusLine").?.object.get("deprecated").?.bool);
    try std.testing.expect(properties.get("model").?.object.get("deprecated").?.bool);
    try std.testing.expect(properties.get("skill_match_fuzzy").?.object.contains("not"));
}

test "the .fx.json schema lists only the project-safe keys" {
    const parsed = try parseSchema(std.testing.allocator, .project);
    defer parsed.deinit();
    const root = parsed.value.object;
    try std.testing.expectEqualStrings(File.project.url(), root.get("$id").?.string);
    try std.testing.expect(!root.contains("$defs"));
    const properties = root.get("properties").?.object;
    for (settings_keys.keys) |key| {
        try std.testing.expectEqual(key.where == .project_safe or key.where == .editor, properties.contains(key.name));
    }
    try std.testing.expect(properties.contains("$schema"));
    try std.testing.expectEqual(@as(i64, 1024), properties.get("max_tool_result_bytes").?.object.get("minimum").?.integer);
}
